#!/usr/bin/env node
/**
 * Generate TypeScript bindings for the OMT protocol from schema/*.schema.json
 * (KTD2: the schema documents are the single source of truth; R3).
 *
 * Output: packages/client-ts/src/generated/<doc>.ts plus an index.ts barrel and
 * problemCodes.ts constants derived from problems.schema.json.
 *
 * Idempotent by construction: documents are processed in a fixed canonical
 * order, declarations are emitted in jstt's deterministic order with a stable
 * banner, and files are written back only when their bytes change.
 *
 * Usage: node scripts/gen-bindings.mjs  (or `pnpm gen` at the repo root)
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const schemaDir = path.join(repoRoot, 'schema')
const outDir = path.join(repoRoot, 'packages', 'client-ts', 'src', 'generated')

/**
 * Canonical ownership order for generated modules: shared vocabulary first,
 * then consumers. A definition duplicated across files (because json-schema-
 * to-typescript inlines cross-file $ref targets) is owned by the earliest
 * module in this list; later modules import it instead of redeclaring.
 */
const DOC_ORDER = [
  'common',
  'envelope',
  'problems',
  'capabilities',
  'events',
  'commands',
  'parity',
]

const GENERATED_BANNER =
  '// @generated by scripts/gen-bindings.mjs from schema/*.schema.json — do not edit.\n' +
  '// Regenerate with `pnpm gen` at the repository root.\n\n'

function pascal(base) {
  return base
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

/**
 * Rewrite internal `$defs` pointers (`#/$defs/X`) to `#/definitions/X`, the
 * container json-schema-to-typescript walks. Cross-file refs are untouched so
 * they resolve against sibling schema files.
 */
function retargetDefs(node) {
  if (Array.isArray(node)) return node.map(retargetDefs)
  if (node && typeof node === 'object') {
    const out = {}
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref' && typeof value === 'string' && value.startsWith('#/$defs/')) {
        out[key] = '#/definitions/' + value.slice('#/$defs/'.length)
      } else {
        out[key] = retargetDefs(value)
      }
    }
    return out
  }
  return node
}

async function compileDocument(base) {
  const doc = JSON.parse(fs.readFileSync(path.join(schemaDir, `${base}.schema.json`), 'utf8'))
  const defs = retargetDefs(doc.$defs ?? {})
  const rootName = `${pascal(base)}ProtocolRoot`
  const wrapper = {
    $schema: doc.$schema,
    title: rootName,
    definitions: defs,
    // json-schema-to-typescript only emits definitions reachable from the
    // root; referencing every def makes the full surface available. The
    // synthetic union itself is stripped below — it is scaffolding, not wire.
    oneOf: Object.keys(defs).map((name) => ({ $ref: `#/definitions/${name}` })),
  }
  const ts = await compile(wrapper, `${base}.ts`, {
    bannerComment: '',
    cwd: schemaDir,
  })
  return { rootName, ts }
}

/**
 * Split jstt output into top-level declaration blocks. jstt emits declarations
 * back-to-back (a JSDoc comment immediately above each `export`, separated
 * from the previous declaration by a single newline), so blocks are recovered
 * by locating every top-level `export` line and pulling in the comment lines
 * directly above it.
 */
function splitDeclarations(ts) {
  const lines = ts.split('\n')
  const starts = []
  lines.forEach((line, index) => {
    if (/^export (?:interface|type|enum) /.test(line)) starts.push(index)
  })

  const blocks = []
  for (let i = 0; i < starts.length; i += 1) {
    const exportLine = starts[i]
    // Walk upward across the contiguous JSDoc comment (if any).
    let blockStart = exportLine
    if (blockStart > 0 && lines[blockStart - 1].trim() === '*/') {
      blockStart -= 1
      while (blockStart > 0 && !lines[blockStart].startsWith('/**')) blockStart -= 1
    }
    const end = i + 1 < starts.length ? starts[i + 1] : lines.length
    const text = lines.slice(blockStart, end).join('\n').trim()
    const name = text.match(/export (?:interface|type|enum) ([A-Za-z0-9_]+)/)?.[1] ?? null
    blocks.push({ name, text })
  }
  return blocks
}

function renderModule({ headerDoc, blocks }) {
  const body = blocks.map((block) => block.text).join('\n\n')
  return `${GENERATED_BANNER}${headerDoc ? `/* ${headerDoc} */\n\n` : ''}${body}\n`
}

async function main() {
  /** name → owning module base, filled as documents are processed. */
  const owner = new Map()
  const outputs = new Map()

  for (const base of DOC_ORDER) {
    const { rootName, ts } = await compileDocument(base)
    let blocks = splitDeclarations(ts)

    // Drop the synthetic oneOf-root union; it exists only to make jstt emit
    // every definition.
    blocks = blocks.filter((block) => block.name !== rootName)
    if (blocks.some((block) => block.name === null || block.name === rootName)) {
      throw new Error(`unparsed declaration block in ${base}.schema.json output`)
    }

    // Ownership pass: keep first-declared definitions, drop duplicates and
    // remember where they live so this module can import them.
    const kept = []
    const imports = new Map() // module base -> Set<name>
    for (const block of blocks) {
      const known = owner.get(block.name)
      if (known === undefined) {
        owner.set(block.name, base)
        kept.push(block)
        continue
      }
      if (known !== base) {
        if (!imports.has(known)) imports.set(known, new Set())
        imports.get(known).add(block.name)
      }
    }

    // Import exactly the foreign names that survive in this module's text.
    const keptText = kept.map((block) => block.text).join('\n\n')
    const importLines = []
    for (const [from, names] of [...imports].sort()) {
      const used = [...names]
        .filter((name) => new RegExp(`\\b${name}\\b`).test(keptText))
        .sort()
      if (used.length > 0) importLines.push(`import type { ${used.join(', ')} } from './${from}.js'`)
    }

    outputs.set(
      base,
      renderModule({
        headerDoc: undefined,
        blocks: kept,
      }).replace(GENERATED_BANNER, GENERATED_BANNER + (importLines.length > 0 ? `${importLines.join('\n')}\n\n` : '')),
    )
  }

  // Derived constants: seeded problem codes from problems.schema.json (R5).
  const problems = JSON.parse(fs.readFileSync(path.join(schemaDir, 'problems.schema.json'), 'utf8'))
  const seedCodes = problems.$defs.SeedProblemCodes.enum
  const registryNames = Object.keys(problems.$defs.SeedProblemRegistry.properties).sort()
  if (JSON.stringify([...seedCodes].sort()) !== JSON.stringify(registryNames)) {
    throw new Error('SeedProblemCodes enum and SeedProblemRegistry properties drifted apart')
  }
  outputs.set(
    'problemCodes',
    [
      GENERATED_BANNER,
      '/** Seeded coarse problem codes (v1); U2 subdivides additively. */',
      `export const SEED_PROBLEM_CODES = [`,
      ...seedCodes.map((code) => `  '${code}',`),
      `] as const`,
      '',
      'export type SeedProblemCode = (typeof SEED_PROBLEM_CODES)[number]',
      '',
      '/** Problem code returned when a peer cannot share the requested MAJOR. */',
      `export const UNSUPPORTED_PROTOCOL_CODE: SeedProblemCode = 'UNSUPPORTED_PROTOCOL'`,
      '',
    ].join('\n'),
  )

  // Barrel.
  const barrelModules = [...DOC_ORDER, 'problemCodes']
  outputs.set(
    'index',
    `${GENERATED_BANNER}${barrelModules.map((base) => `export * from './${base}.js'`).join('\n')}\n`,
  )

  fs.mkdirSync(outDir, { recursive: true })
  let written = 0
  for (const [base, content] of outputs) {
    const dest = path.join(outDir, `${base}.ts`)
    const existing = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : undefined
    if (existing !== content) {
      fs.writeFileSync(dest, content)
      written += 1
    }
  }

  // Prune stale files no longer produced (e.g. after renaming a document).
  for (const entry of fs.readdirSync(outDir)) {
    if (entry.endsWith('.ts') && !outputs.has(entry.replace(/\.ts$/, ''))) {
      fs.rmSync(path.join(outDir, entry))
      written += 1
    }
  }

  console.log(
    `gen-bindings: ${outputs.size} modules from ${DOC_ORDER.length} schema documents ` +
      `(${written} changed)`,
  )
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
